-- Typed staging and issue objects. Staging fields remain nullable so rejected
-- mandatory values can be represented and quarantined without data loss.
USE SCHEMA SKYPOINTS_ASSESSMENT;

CREATE TABLE IF NOT EXISTS MEMBER_STAGING (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    SOURCE_CODE VARCHAR(32) NOT NULL,
    SOURCE_FILENAME VARCHAR(1024) NOT NULL,
    SOURCE_SHEET VARCHAR(255),
    SOURCE_SHEET_KEY VARCHAR(255) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38, 0) NOT NULL,
    AS_OF_DATE DATE NOT NULL,
    SOURCE_COLUMNS_PRESENT ARRAY NOT NULL,
    RAW_VALUES VARIANT NOT NULL,
    MEMBER_NAME VARCHAR(255),
    MEMBER_NAME_RAW VARCHAR,
    MEMBER_ID VARCHAR(18),
    MEMBER_ID_RAW VARCHAR,
    ENROLLMENT_DATE DATE,
    ENROLLMENT_DATE_RAW VARCHAR,
    ENROLLMENT_DATE_STATUS VARCHAR(16) NOT NULL,
    LAST_FLIGHT_DATE DATE,
    LAST_FLIGHT_DATE_RAW VARCHAR,
    LAST_FLIGHT_DATE_STATUS VARCHAR(16) NOT NULL,
    TIER_CODE CHAR(5),
    TIER_CODE_RAW VARCHAR,
    AGENT_NAME CHAR(255),
    AGENT_NAME_RAW VARCHAR,
    STATE CHAR(5),
    STATE_RAW VARCHAR,
    COUNTRY CHAR(5),
    COUNTRY_RAW VARCHAR,
    POST_CODE NUMBER(5, 0),
    POST_CODE_RAW VARCHAR,
    DOB DATE,
    DOB_RAW VARCHAR,
    DOB_STATUS VARCHAR(16) NOT NULL,
    ACTIVE_MEMBER CHAR(1),
    ACTIVE_MEMBER_RAW VARCHAR,
    AGE NUMBER(38, 0),
    STALE_MEMBER BOOLEAN,
    ROUTED_COUNTRY_CODE VARCHAR(3),
    ROUTING_METHOD VARCHAR(64),
    MEMBER_NAME_KEY_COUNT NUMBER(38, 0) NOT NULL,
    SOURCE_MEMBER_ID_COUNT NUMBER(38, 0) NOT NULL,
    DISPOSITION VARCHAR(16) NOT NULL,
    CONSTRAINT PK_MEMBER_STAGING PRIMARY KEY
        (RUN_ID, ARTIFACT_ID, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER) NOT ENFORCED,
    CONSTRAINT FK_MEMBER_STAGING_RAW FOREIGN KEY
        (RUN_ID, ARTIFACT_ID, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER)
        REFERENCES RAW_MEMBER_LANDING
        (RUN_ID, ARTIFACT_ID, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER) NOT ENFORCED,
    CONSTRAINT CK_MEMBER_STAGING_DISPOSITION CHECK
        (DISPOSITION IN ('ACCEPTED', 'WARNING', 'QUARANTINED'))
);

CREATE TABLE IF NOT EXISTS REDEMPTION_PARENT_STAGING (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    PAYLOAD_INDEX NUMBER(38, 0) NOT NULL,
    PARENT_MEMBER_ID VARCHAR,
    FEED_DATE_RAW VARIANT,
    FEED_DATE DATE,
    TRANSACTION_ARRAY_PRESENT BOOLEAN NOT NULL,
    TRANSACTION_COUNT NUMBER(38, 0) NOT NULL,
    DISPOSITION VARCHAR(16) NOT NULL,
    CONSTRAINT PK_REDEMPTION_PARENT_STAGING PRIMARY KEY
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX) NOT ENFORCED,
    CONSTRAINT FK_REDEMPTION_PARENT_RAW FOREIGN KEY
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX)
        REFERENCES RAW_REDEMPTION_LANDING
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX) NOT ENFORCED,
    CONSTRAINT CK_REDEMPTION_PARENT_DISPOSITION CHECK
        (DISPOSITION IN ('ACCEPTED', 'WARNING', 'QUARANTINED'))
);

CREATE TABLE IF NOT EXISTS REDEMPTION_STAGING (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    PAYLOAD_INDEX NUMBER(38, 0) NOT NULL,
    TRANSACTION_INDEX NUMBER(38, 0) NOT NULL,
    MEMBER_ID VARCHAR,
    FEED_DATE_RAW VARIANT,
    FEED_DATE DATE,
    TXN_ID VARCHAR,
    TXN_DATE_RAW VARIANT,
    TXN_DATE DATE,
    PARTNER VARCHAR,
    MILES_REDEEMED_RAW VARIANT,
    MILES_REDEEMED NUMBER(38, 0),
    STATUS VARCHAR,
    RAW_TRANSACTION VARIANT NOT NULL,
    MATCHED_MEMBER_RUN_ID VARCHAR(100),
    MATCHED_MEMBER_ARTIFACT_ID VARCHAR(256),
    MATCHED_MEMBER_SOURCE_CODE VARCHAR(32),
    MATCHED_MEMBER_SHEET_KEY VARCHAR(255),
    MATCHED_MEMBER_SOURCE_ROW_NUMBER NUMBER(38, 0),
    DISPOSITION VARCHAR(16) NOT NULL,
    CONSTRAINT PK_REDEMPTION_STAGING PRIMARY KEY
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX, TRANSACTION_INDEX) NOT ENFORCED,
    CONSTRAINT FK_REDEMPTION_STAGING_PARENT FOREIGN KEY
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX)
        REFERENCES REDEMPTION_PARENT_STAGING
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX) NOT ENFORCED,
    CONSTRAINT FK_REDEMPTION_CONFIRMED_MEMBER FOREIGN KEY
        (MATCHED_MEMBER_RUN_ID, MATCHED_MEMBER_ARTIFACT_ID,
         MATCHED_MEMBER_SHEET_KEY, MATCHED_MEMBER_SOURCE_ROW_NUMBER)
        REFERENCES MEMBER_STAGING
        (RUN_ID, ARTIFACT_ID, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER) NOT ENFORCED,
    CONSTRAINT CK_REDEMPTION_MEMBER_LOCATOR CHECK (
        (MATCHED_MEMBER_RUN_ID IS NULL AND MATCHED_MEMBER_ARTIFACT_ID IS NULL
         AND MATCHED_MEMBER_SOURCE_CODE IS NULL AND MATCHED_MEMBER_SHEET_KEY IS NULL
         AND MATCHED_MEMBER_SOURCE_ROW_NUMBER IS NULL)
        OR
        (MATCHED_MEMBER_RUN_ID IS NOT NULL AND MATCHED_MEMBER_ARTIFACT_ID IS NOT NULL
         AND MATCHED_MEMBER_SOURCE_CODE IS NOT NULL AND MATCHED_MEMBER_SHEET_KEY IS NOT NULL
         AND MATCHED_MEMBER_SOURCE_ROW_NUMBER IS NOT NULL)
    ),
    CONSTRAINT CK_REDEMPTION_STAGING_DISPOSITION CHECK
        (DISPOSITION IN ('ACCEPTED', 'WARNING', 'QUARANTINED'))
);

CREATE TABLE IF NOT EXISTS DATA_QUALITY_ISSUE (
    ISSUE_ID VARCHAR(64) NOT NULL,
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    ENTITY_TYPE VARCHAR(32) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38, 0),
    SOURCE_SHEET_KEY VARCHAR(255),
    PAYLOAD_INDEX NUMBER(38, 0),
    TRANSACTION_INDEX NUMBER(38, 0),
    ISSUE_ORDINAL NUMBER(9, 0) NOT NULL,
    ISSUE_CATEGORY VARCHAR(32) NOT NULL,
    RULE_CODE VARCHAR(128) NOT NULL,
    SEVERITY VARCHAR(16) NOT NULL,
    FIELD_NAME VARCHAR(128),
    DETAIL VARCHAR NOT NULL,
    CREATED_AT_UTC TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_DATA_QUALITY_ISSUE PRIMARY KEY (ISSUE_ID) NOT ENFORCED,
    CONSTRAINT CK_DATA_QUALITY_SEVERITY CHECK (SEVERITY IN ('WARNING', 'ERROR'))
);

COMMENT ON COLUMN MEMBER_STAGING.MEMBER_NAME IS
    'Assessment marks Member Name as a key. Provisional local uniqueness scope is RUN_ID + BATCH_ID + SOURCE_CODE; duplicate rows stay in staging and are quarantined.';
COMMENT ON COLUMN MEMBER_STAGING.MEMBER_ID IS
    'Assessment-mandatory VARCHAR(18), not a key. Source-local values are not global identity.';
COMMENT ON COLUMN REDEMPTION_STAGING.MATCHED_MEMBER_RUN_ID IS
    'Only populated from an explicitly confirmed source-owner mapping; never inferred from names or local IDs.';
