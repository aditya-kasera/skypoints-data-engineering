-- Snowflake raw landing and run/artifact audit objects.
-- Run in a database where the executing role can create schemas and tables.
CREATE SCHEMA IF NOT EXISTS SKYPOINTS_ASSESSMENT;
USE SCHEMA SKYPOINTS_ASSESSMENT;

CREATE TABLE IF NOT EXISTS PIPELINE_RUN (
    RUN_ID VARCHAR(100) NOT NULL,
    STARTED_AT_UTC TIMESTAMP_TZ NOT NULL,
    FINISHED_AT_UTC TIMESTAMP_TZ,
    RUN_STATUS VARCHAR(16) NOT NULL,
    AS_OF_DATE DATE NOT NULL,
    CONSTRAINT PK_PIPELINE_RUN PRIMARY KEY (RUN_ID) NOT ENFORCED,
    CONSTRAINT CK_PIPELINE_RUN_STATUS CHECK (RUN_STATUS IN ('RUNNING', 'SUCCEEDED', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS INPUT_ARTIFACT (
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    SOURCE_KIND VARCHAR(16) NOT NULL,
    SOURCE_IDENTITY VARCHAR(255) NOT NULL,
    CONTENT_SHA256 VARCHAR(64) NOT NULL,
    SCHEMA_MANIFEST VARIANT,
    CONSTRAINT PK_INPUT_ARTIFACT PRIMARY KEY (ARTIFACT_ID) NOT ENFORCED,
    CONSTRAINT CK_INPUT_ARTIFACT_SHA CHECK (LENGTH(CONTENT_SHA256) = 64)
);

CREATE TABLE IF NOT EXISTS RUN_INPUT (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    SOURCE_FILENAME VARCHAR(1024) NOT NULL,
    FEED_GENERATED_AT_UTC TIMESTAMP_TZ,
    INGESTED_AT_UTC TIMESTAMP_TZ NOT NULL,
    INPUT_STATUS VARCHAR(16) NOT NULL,
    FAILURE_DETAIL VARCHAR,
    CONSTRAINT PK_RUN_INPUT PRIMARY KEY (RUN_ID, ARTIFACT_ID) NOT ENFORCED,
    CONSTRAINT FK_RUN_INPUT_RUN FOREIGN KEY (RUN_ID) REFERENCES PIPELINE_RUN(RUN_ID) NOT ENFORCED,
    CONSTRAINT FK_RUN_INPUT_ARTIFACT FOREIGN KEY (ARTIFACT_ID) REFERENCES INPUT_ARTIFACT(ARTIFACT_ID) NOT ENFORCED,
    CONSTRAINT CK_RUN_INPUT_STATUS CHECK (INPUT_STATUS IN ('PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED'))
);

CREATE TABLE IF NOT EXISTS RAW_MEMBER_LANDING (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    SOURCE_CODE VARCHAR(32) NOT NULL,
    SOURCE_FILENAME VARCHAR(1024) NOT NULL,
    SOURCE_SHEET VARCHAR(255),
    SOURCE_SHEET_KEY VARCHAR(255) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38, 0) NOT NULL,
    INGESTED_AT_UTC TIMESTAMP_TZ NOT NULL,
    FEED_GENERATED_AT_UTC TIMESTAMP_TZ,
    SOURCE_SHA256 VARCHAR(64) NOT NULL,
    SCHEMA_FINGERPRINT VARCHAR(64) NOT NULL,
    SOURCE_COLUMNS_PRESENT ARRAY NOT NULL,
    RAW_RECORD_TEXT VARCHAR,
    RAW_VALUES VARIANT NOT NULL,
    NORMALIZED_VALUES VARIANT,
    CONSTRAINT PK_RAW_MEMBER_LANDING PRIMARY KEY
        (RUN_ID, ARTIFACT_ID, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER) NOT ENFORCED,
    CONSTRAINT FK_RAW_MEMBER_RUN_INPUT FOREIGN KEY (RUN_ID, ARTIFACT_ID)
        REFERENCES RUN_INPUT(RUN_ID, ARTIFACT_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS RAW_REDEMPTION_LANDING (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    SOURCE_FILENAME VARCHAR(1024) NOT NULL,
    PAYLOAD_INDEX NUMBER(38, 0) NOT NULL,
    INGESTED_AT_UTC TIMESTAMP_TZ NOT NULL,
    FEED_GENERATED_AT_UTC TIMESTAMP_TZ,
    SOURCE_SHA256 VARCHAR(64) NOT NULL,
    RAW_PAYLOAD_TEXT VARCHAR NOT NULL,
    PAYLOAD VARIANT,
    JSON_PARSE_ERROR VARCHAR,
    CONSTRAINT PK_RAW_REDEMPTION_LANDING PRIMARY KEY
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX) NOT ENFORCED,
    CONSTRAINT FK_RAW_REDEMPTION_RUN_INPUT FOREIGN KEY (RUN_ID, ARTIFACT_ID)
        REFERENCES RUN_INPUT(RUN_ID, ARTIFACT_ID) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS RUN_RECONCILIATION (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    SCOPE VARCHAR(32) NOT NULL,
    READ_COUNT NUMBER(38, 0) NOT NULL,
    ACCEPTED_COUNT NUMBER(38, 0) NOT NULL,
    WARNED_COUNT NUMBER(38, 0) NOT NULL,
    QUARANTINED_COUNT NUMBER(38, 0) NOT NULL,
    TRANSFORMED_COUNT NUMBER(38, 0) NOT NULL,
    UNMATCHED_COUNT NUMBER(38, 0) NOT NULL,
    RAW_PERSISTED_COUNT NUMBER(38, 0) NOT NULL,
    CURATED_PERSISTED_COUNT NUMBER(38, 0) NOT NULL,
    RECONCILED_AT_UTC TIMESTAMP_TZ NOT NULL,
    CONSTRAINT PK_RUN_RECONCILIATION PRIMARY KEY (RUN_ID, ARTIFACT_ID, SCOPE) NOT ENFORCED,
    CONSTRAINT FK_RECON_RUN_INPUT FOREIGN KEY (RUN_ID, ARTIFACT_ID)
        REFERENCES RUN_INPUT(RUN_ID, ARTIFACT_ID) NOT ENFORCED,
    CONSTRAINT CK_RECON_SCOPE CHECK
        (SCOPE IN ('member_record', 'redemption_parent', 'redemption_transaction')),
    CONSTRAINT CK_RECON_COUNTS CHECK (
        READ_COUNT = ACCEPTED_COUNT + WARNED_COUNT + QUARANTINED_COUNT
        AND UNMATCHED_COUNT <= READ_COUNT
        AND TRANSFORMED_COUNT <= READ_COUNT
        AND CURATED_PERSISTED_COUNT <= READ_COUNT
    )
);

COMMENT ON TABLE RAW_MEMBER_LANDING IS
    'One preserved source row per run/artifact/row locator. RAW_VALUES retains source values; NORMALIZED_VALUES optionally carries adapter-normalized values for typed parsing. Do not treat ingestion time as member recency.';
COMMENT ON TABLE RAW_REDEMPTION_LANDING IS
    'One parent payload per source position. RAW_PAYLOAD_TEXT preserves malformed JSON; PAYLOAD is TRY_PARSE_JSON output when valid.';
COMMENT ON COLUMN RUN_INPUT.FEED_GENERATED_AT_UTC IS
    'Nullable producer-declared artifact generation time; not a member business-effective timestamp.';
COMMENT ON COLUMN RUN_INPUT.INGESTED_AT_UTC IS
    'Operational ingestion time in UTC; never use as business recency.';
