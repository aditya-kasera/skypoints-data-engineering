-- Parse retained raw text with TRY_PARSE_JSON, then FLATTEN every valid array
-- element. Invalid parents remain in RAW_REDEMPTION_LANDING with raw text.
USE SCHEMA SKYPOINTS_ASSESSMENT;
SET RUN_ID = 'REPLACE_WITH_RUN_ID';

CREATE TABLE IF NOT EXISTS FLATTENED_REDEMPTION (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    SOURCE_FILENAME VARCHAR(1024) NOT NULL,
    PAYLOAD_INDEX NUMBER(38, 0) NOT NULL,
    TRANSACTION_INDEX NUMBER(38, 0) NOT NULL,
    MEMBER_ID VARCHAR,
    FEED_DATE_RAW VARIANT,
    FEED_DATE DATE,
    TXN_ID VARCHAR,
    TXN_DATE_RAW VARIANT,
    TXN_DATE DATE,
    PARTNER VARCHAR,
    MILES_REDEEMED_RAW VARIANT,
    MILES_REDEEMED NUMBER(38, 0),
    STATUS VARCHAR,
    RAW_TRANSACTION VARIANT NOT NULL,
    MATCHED_MEMBER_RUN_ID VARCHAR(100),
    MATCHED_MEMBER_ARTIFACT_ID VARCHAR(256),
    MATCHED_MEMBER_SOURCE_CODE VARCHAR(32),
    MATCHED_MEMBER_SHEET_KEY VARCHAR(255),
    MATCHED_MEMBER_SOURCE_ROW_NUMBER NUMBER(38, 0),
    DISPOSITION VARCHAR(16) NOT NULL,
    CONSTRAINT PK_FLATTENED_REDEMPTION PRIMARY KEY
        (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX, TRANSACTION_INDEX) NOT ENFORCED,
    CONSTRAINT FK_FLATTENED_CONFIRMED_MEMBER FOREIGN KEY
        (MATCHED_MEMBER_RUN_ID, MATCHED_MEMBER_ARTIFACT_ID,
         MATCHED_MEMBER_SHEET_KEY, MATCHED_MEMBER_SOURCE_ROW_NUMBER)
        REFERENCES MEMBER_STAGING
        (RUN_ID, ARTIFACT_ID, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER) NOT ENFORCED,
    CONSTRAINT CK_FLATTENED_MEMBER_LOCATOR CHECK (
        (MATCHED_MEMBER_RUN_ID IS NULL AND MATCHED_MEMBER_ARTIFACT_ID IS NULL
         AND MATCHED_MEMBER_SOURCE_CODE IS NULL AND MATCHED_MEMBER_SHEET_KEY IS NULL
         AND MATCHED_MEMBER_SOURCE_ROW_NUMBER IS NULL)
        OR
        (MATCHED_MEMBER_RUN_ID IS NOT NULL AND MATCHED_MEMBER_ARTIFACT_ID IS NOT NULL
         AND MATCHED_MEMBER_SOURCE_CODE IS NOT NULL AND MATCHED_MEMBER_SHEET_KEY IS NOT NULL
         AND MATCHED_MEMBER_SOURCE_ROW_NUMBER IS NOT NULL)
    )
);

CREATE OR REPLACE VIEW CURATED_REDEMPTION AS
SELECT F.*
FROM FLATTENED_REDEMPTION F
JOIN REDEMPTION_PARENT_STAGING P
  ON P.RUN_ID = F.RUN_ID AND P.ARTIFACT_ID = F.ARTIFACT_ID
 AND P.PAYLOAD_INDEX = F.PAYLOAD_INDEX
WHERE F.DISPOSITION <> 'QUARANTINED'
  AND P.DISPOSITION <> 'QUARANTINED';

CREATE OR REPLACE TEMP TABLE REDEMPTION_PARENT_CANDIDATE AS
SELECT R.RUN_ID, R.ARTIFACT_ID, R.BATCH_ID, R.PAYLOAD_INDEX,
       R.PAYLOAD:"member_id"::VARCHAR AS PARENT_MEMBER_ID,
       R.PAYLOAD:"feed_date" AS FEED_DATE_RAW,
       TRY_TO_DATE(R.PAYLOAD:"feed_date"::VARCHAR, 'YYYYMMDD') AS FEED_DATE,
       COALESCE(TYPEOF(R.PAYLOAD:"redemptions") = 'ARRAY', FALSE) AS TRANSACTION_ARRAY_PRESENT,
       IFF(TYPEOF(R.PAYLOAD:"redemptions") = 'ARRAY', ARRAY_SIZE(R.PAYLOAD:"redemptions"), 0) AS TRANSACTION_COUNT,
       CASE WHEN R.JSON_PARSE_ERROR IS NOT NULL OR R.PAYLOAD IS NULL
                  OR TYPEOF(R.PAYLOAD) <> 'OBJECT'
                  OR NULLIF(TRIM(R.PAYLOAD:"member_id"::VARCHAR), '') IS NULL
                  OR TYPEOF(R.PAYLOAD:"member_id") <> 'VARCHAR'
                  OR TRY_TO_DATE(R.PAYLOAD:"feed_date"::VARCHAR, 'YYYYMMDD') IS NULL
                  OR NOT COALESCE(TYPEOF(R.PAYLOAD:"redemptions") = 'ARRAY', FALSE)
            THEN 'QUARANTINED' ELSE 'ACCEPTED' END AS DISPOSITION
FROM RAW_REDEMPTION_LANDING R
WHERE R.RUN_ID = $RUN_ID;

CREATE OR REPLACE TEMP TABLE REDEMPTION_CANDIDATE AS
WITH FLAT AS (
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.BATCH_ID, R.SOURCE_FILENAME,
           P.PAYLOAD_INDEX, F.INDEX + 1 AS TRANSACTION_INDEX,
           P.PARENT_MEMBER_ID AS MEMBER_ID, P.FEED_DATE_RAW, P.FEED_DATE,
           P.DISPOSITION AS PARENT_DISPOSITION,
           F.VALUE:"txn_id"::VARCHAR AS TXN_ID,
           F.VALUE:"txn_date" AS TXN_DATE_RAW,
           TRY_TO_DATE(F.VALUE:"txn_date"::VARCHAR, 'YYYYMMDD') AS TXN_DATE,
           F.VALUE:"partner"::VARCHAR AS PARTNER,
           F.VALUE:"miles_redeemed" AS MILES_REDEEMED_RAW,
           TRY_TO_DECIMAL(F.VALUE:"miles_redeemed"::VARCHAR, 38, 6) AS MILES_DECIMAL,
           F.VALUE:"status"::VARCHAR AS STATUS,
           F.VALUE AS RAW_TRANSACTION
    FROM RAW_REDEMPTION_LANDING R
    JOIN REDEMPTION_PARENT_CANDIDATE P
      ON P.RUN_ID = R.RUN_ID AND P.ARTIFACT_ID = R.ARTIFACT_ID AND P.PAYLOAD_INDEX = R.PAYLOAD_INDEX,
         LATERAL FLATTEN(INPUT => R.PAYLOAD:"redemptions") F
    WHERE R.RUN_ID = $RUN_ID AND P.TRANSACTION_ARRAY_PRESENT
), TYPED AS (
    SELECT F.*,
        CASE WHEN TYPEOF(MILES_REDEEMED_RAW) IN ('INTEGER', 'DECIMAL', 'DOUBLE')
                   AND MILES_DECIMAL = TRUNC(MILES_DECIMAL)
             THEN MILES_DECIMAL::NUMBER(38,0) END AS MILES_REDEEMED,
        COUNT_IF(NULLIF(TRIM(TXN_ID), '') IS NOT NULL) OVER
            (PARTITION BY RUN_ID, BATCH_ID, TXN_ID) AS TXN_ID_COUNT
    FROM FLAT F
)
SELECT T.*,
    CASE WHEN PARENT_DISPOSITION = 'QUARANTINED'
               OR NULLIF(TRIM(TXN_ID), '') IS NULL OR TXN_DATE IS NULL
               OR NULLIF(TRIM(PARTNER), '') IS NULL
               OR MILES_REDEEMED IS NULL OR NULLIF(TRIM(STATUS), '') IS NULL
               OR TXN_ID_COUNT > 1
         THEN 'QUARANTINED'
         WHEN MEMBER_ID IS NOT NULL OR MILES_REDEEMED <= 0 THEN 'WARNING'
         ELSE 'ACCEPTED' END AS DISPOSITION
FROM TYPED T;

BEGIN TRANSACTION;
DELETE FROM REDEMPTION_STAGING WHERE RUN_ID = $RUN_ID;
DELETE FROM REDEMPTION_PARENT_STAGING WHERE RUN_ID = $RUN_ID;
DELETE FROM FLATTENED_REDEMPTION WHERE RUN_ID = $RUN_ID;
DELETE FROM DATA_QUALITY_ISSUE WHERE RUN_ID = $RUN_ID AND ENTITY_TYPE IN ('REDEMPTION_PARENT', 'REDEMPTION_TRANSACTION');

INSERT INTO REDEMPTION_PARENT_STAGING (
    RUN_ID, ARTIFACT_ID, BATCH_ID, PAYLOAD_INDEX, PARENT_MEMBER_ID,
    FEED_DATE_RAW, FEED_DATE, TRANSACTION_ARRAY_PRESENT, TRANSACTION_COUNT, DISPOSITION
)
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, PAYLOAD_INDEX, PARENT_MEMBER_ID,
       FEED_DATE_RAW, FEED_DATE, TRANSACTION_ARRAY_PRESENT, TRANSACTION_COUNT, DISPOSITION
FROM REDEMPTION_PARENT_CANDIDATE;

-- Parent validation findings include syntax failures retained as raw text,
-- absent/invalid required parent values, and a missing/non-array child field.
INSERT INTO DATA_QUALITY_ISSUE
SELECT SHA2(CONCAT_WS('|', RUN_ID, ARTIFACT_ID, 'REDEMPTION_PARENT', PAYLOAD_INDEX, RULE_CODE), 256),
       RUN_ID, ARTIFACT_ID, 'REDEMPTION_PARENT', NULL, NULL, PAYLOAD_INDEX, NULL,
       ROW_NUMBER() OVER (PARTITION BY RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX ORDER BY RULE_CODE),
       'validation', RULE_CODE, 'ERROR', FIELD_NAME, DETAIL, CURRENT_TIMESTAMP()::TIMESTAMP_TZ
FROM (
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.PAYLOAD_INDEX,
           'JSON_SYNTAX_INVALID' AS RULE_CODE, 'payload' AS FIELD_NAME,
           'Raw payload could not be parsed as JSON; original text is retained.' AS DETAIL
    FROM REDEMPTION_PARENT_STAGING P
    JOIN RAW_REDEMPTION_LANDING R USING (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX)
    WHERE P.RUN_ID = $RUN_ID AND R.JSON_PARSE_ERROR IS NOT NULL
    UNION ALL
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.PAYLOAD_INDEX,
           'JSON_TOP_LEVEL_INVALID', 'payload', 'JSON must parse to a top-level object.'
    FROM REDEMPTION_PARENT_STAGING P
    JOIN RAW_REDEMPTION_LANDING R USING (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX)
    WHERE P.RUN_ID = $RUN_ID AND R.JSON_PARSE_ERROR IS NULL
      AND R.PAYLOAD IS NOT NULL AND TYPEOF(R.PAYLOAD) <> 'OBJECT'
    UNION ALL
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.PAYLOAD_INDEX,
           'PARENT_MEMBER_ID_REQUIRED', 'member_id', 'Required parent member_id is absent or blank.'
    FROM REDEMPTION_PARENT_STAGING P
    WHERE P.RUN_ID = $RUN_ID AND NULLIF(TRIM(P.PARENT_MEMBER_ID), '') IS NULL
    UNION ALL
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.PAYLOAD_INDEX,
           'PARENT_MEMBER_ID_TYPE_INVALID', 'member_id', 'Parent member_id must be a JSON string.'
    FROM REDEMPTION_PARENT_STAGING P
    JOIN RAW_REDEMPTION_LANDING R USING (RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX)
    WHERE P.RUN_ID = $RUN_ID AND R.PAYLOAD:"member_id" IS NOT NULL
      AND TYPEOF(R.PAYLOAD:"member_id") <> 'VARCHAR'
    UNION ALL
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.PAYLOAD_INDEX,
           'PARENT_FEED_DATE_INVALID', 'feed_date', 'feed_date is not a valid YYYYMMDD calendar date.'
    FROM REDEMPTION_PARENT_STAGING P
    WHERE P.RUN_ID = $RUN_ID AND P.FEED_DATE IS NULL
    UNION ALL
    SELECT P.RUN_ID, P.ARTIFACT_ID, P.PAYLOAD_INDEX,
           'REDEMPTIONS_ARRAY_REQUIRED', 'redemptions', 'redemptions is absent or is not an array.'
    FROM REDEMPTION_PARENT_STAGING P
    WHERE P.RUN_ID = $RUN_ID AND NOT P.TRANSACTION_ARRAY_PRESENT
) V;

INSERT INTO REDEMPTION_STAGING (
    RUN_ID, ARTIFACT_ID, BATCH_ID, PAYLOAD_INDEX, TRANSACTION_INDEX,
    MEMBER_ID, FEED_DATE_RAW, FEED_DATE, TXN_ID, TXN_DATE_RAW, TXN_DATE,
    PARTNER, MILES_REDEEMED_RAW, MILES_REDEEMED, STATUS, RAW_TRANSACTION,
    MATCHED_MEMBER_RUN_ID, MATCHED_MEMBER_ARTIFACT_ID, MATCHED_MEMBER_SOURCE_CODE,
    MATCHED_MEMBER_SHEET_KEY, MATCHED_MEMBER_SOURCE_ROW_NUMBER, DISPOSITION
)
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, PAYLOAD_INDEX, TRANSACTION_INDEX,
       MEMBER_ID, FEED_DATE_RAW, FEED_DATE, TXN_ID, TXN_DATE_RAW, TXN_DATE,
       PARTNER, MILES_REDEEMED_RAW, MILES_REDEEMED, STATUS, RAW_TRANSACTION,
       NULL, NULL, NULL, NULL, NULL, DISPOSITION
FROM REDEMPTION_CANDIDATE;

INSERT INTO DATA_QUALITY_ISSUE
SELECT SHA2(CONCAT_WS('|', RUN_ID, ARTIFACT_ID, 'REDEMPTION_TRANSACTION',
           PAYLOAD_INDEX, TRANSACTION_INDEX, RULE_CODE), 256),
       RUN_ID, ARTIFACT_ID, 'REDEMPTION_TRANSACTION', NULL, NULL,
       PAYLOAD_INDEX, TRANSACTION_INDEX,
       ROW_NUMBER() OVER (PARTITION BY RUN_ID, ARTIFACT_ID, PAYLOAD_INDEX, TRANSACTION_INDEX ORDER BY RULE_CODE),
       ISSUE_CATEGORY, RULE_CODE, SEVERITY, FIELD_NAME, DETAIL, CURRENT_TIMESTAMP()::TIMESTAMP_TZ
FROM (
    SELECT *, 'validation' AS ISSUE_CATEGORY, 'ERROR' AS SEVERITY,
           'txn_id' AS FIELD_NAME, 'TXN_ID_REQUIRED' AS RULE_CODE,
           'Required transaction ID is absent or blank.' AS DETAIL
    FROM REDEMPTION_CANDIDATE WHERE NULLIF(TRIM(TXN_ID), '') IS NULL
    UNION ALL
    SELECT *, 'validation', 'ERROR', 'txn_date', 'TXN_DATE_INVALID',
           'txn_date is not a valid YYYYMMDD calendar date.'
    FROM REDEMPTION_CANDIDATE WHERE TXN_DATE IS NULL
    UNION ALL
    SELECT *, 'validation', 'ERROR', 'partner', 'PARTNER_REQUIRED',
           'Required partner is absent or blank.'
    FROM REDEMPTION_CANDIDATE WHERE NULLIF(TRIM(PARTNER), '') IS NULL
    UNION ALL
    SELECT *, 'validation', 'ERROR', 'miles_redeemed', 'MILES_NOT_INTEGER',
           'Miles must be a numeric integer; original value remains in RAW_TRANSACTION.'
    FROM REDEMPTION_CANDIDATE WHERE MILES_REDEEMED IS NULL
    UNION ALL
    SELECT *, 'validation', 'ERROR', 'status', 'STATUS_REQUIRED',
           'Required status is absent or blank; no complete status domain is assumed.'
    FROM REDEMPTION_CANDIDATE WHERE NULLIF(TRIM(STATUS), '') IS NULL
    UNION ALL
    SELECT *, 'validation', 'ERROR', 'txn_id', 'DUPLICATE_TXN_ID_IN_BATCH',
           'Duplicate transaction ID within this run/batch scope; every matching row is quarantined.'
    FROM REDEMPTION_CANDIDATE WHERE TXN_ID_COUNT > 1
    UNION ALL
    SELECT *, 'referential_integrity', 'WARNING', 'member_id', 'MEMBER_REFERENCE_UNMATCHED',
           'No confirmed member-record mapping was supplied for an eligible transaction; transaction is retained.'
    FROM REDEMPTION_CANDIDATE
    WHERE PARENT_DISPOSITION = 'ACCEPTED'
      AND DISPOSITION <> 'QUARANTINED'
      AND MEMBER_ID IS NOT NULL
    UNION ALL
    SELECT *, 'validation', 'WARNING', 'miles_redeemed', 'NON_POSITIVE_MILES',
           'Non-positive miles are flagged provisionally; reversal/zero-value rules require confirmation.'
    FROM REDEMPTION_CANDIDATE WHERE MILES_REDEEMED <= 0
) Q;

INSERT INTO FLATTENED_REDEMPTION
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_FILENAME, PAYLOAD_INDEX, TRANSACTION_INDEX,
       MEMBER_ID, FEED_DATE_RAW, FEED_DATE, TXN_ID, TXN_DATE_RAW, TXN_DATE,
       PARTNER, MILES_REDEEMED_RAW, MILES_REDEEMED, STATUS, RAW_TRANSACTION,
       MATCHED_MEMBER_RUN_ID, MATCHED_MEMBER_ARTIFACT_ID, MATCHED_MEMBER_SOURCE_CODE,
       MATCHED_MEMBER_SHEET_KEY, MATCHED_MEMBER_SOURCE_ROW_NUMBER, DISPOSITION
FROM REDEMPTION_STAGING
WHERE RUN_ID = $RUN_ID;
COMMIT;

