-- Set RUN_ID and AS_OF_DATE for each execution. No CURRENT_DATE dependency is
-- used for business derivations; timestamps below are operational audit times.
USE SCHEMA SKYPOINTS_ASSESSMENT;
SET RUN_ID = 'REPLACE_WITH_RUN_ID';
SET AS_OF_DATE = '2024-01-15'::DATE;

CREATE OR REPLACE TEMP TABLE MEMBER_CANDIDATE AS
WITH BASE AS (
    SELECT
        R.RUN_ID, R.ARTIFACT_ID, R.BATCH_ID, R.SOURCE_CODE, R.SOURCE_FILENAME,
        R.SOURCE_SHEET, R.SOURCE_SHEET_KEY, R.SOURCE_ROW_NUMBER,
        R.SOURCE_COLUMNS_PRESENT, R.RAW_VALUES, R.NORMALIZED_VALUES,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN R.RAW_VALUES:"Member Name"::VARCHAR
            WHEN 'IND' THEN R.RAW_VALUES:"Name"::VARCHAR
            WHEN 'USA' THEN R.RAW_VALUES:"Name"::VARCHAR
        END AS MEMBER_NAME_RAW,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN R.RAW_VALUES:"Unique ID"::VARCHAR
            WHEN 'IND' THEN R.RAW_VALUES:"ID"::VARCHAR
            WHEN 'USA' THEN R.RAW_VALUES:"ID"::VARCHAR
        END AS MEMBER_ID_RAW,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN R.RAW_VALUES:"Date of Enrollment"::VARCHAR
            WHEN 'IND' THEN R.RAW_VALUES:"EnrollmentDate"::VARCHAR
            WHEN 'USA' THEN R.RAW_VALUES:"EnrollmentDate"::VARCHAR
        END AS ENROLLMENT_DATE_RAW,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN COALESCE(R.NORMALIZED_VALUES:"Date of Enrollment"::VARCHAR, R.RAW_VALUES:"Date of Enrollment"::VARCHAR)
            WHEN 'IND' THEN COALESCE(R.NORMALIZED_VALUES:"EnrollmentDate"::VARCHAR, R.RAW_VALUES:"EnrollmentDate"::VARCHAR)
            WHEN 'USA' THEN COALESCE(R.NORMALIZED_VALUES:"EnrollmentDate"::VARCHAR, R.RAW_VALUES:"EnrollmentDate"::VARCHAR)
        END AS ENROLLMENT_DATE_PARSE_VALUE,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN R.RAW_VALUES:"Date of Flight"::VARCHAR
            WHEN 'IND' THEN R.RAW_VALUES:"Flight Date"::VARCHAR
            WHEN 'USA' THEN R.RAW_VALUES:"FlightDate"::VARCHAR
        END AS LAST_FLIGHT_DATE_RAW,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN COALESCE(R.NORMALIZED_VALUES:"Date of Flight"::VARCHAR, R.RAW_VALUES:"Date of Flight"::VARCHAR)
            WHEN 'IND' THEN COALESCE(R.NORMALIZED_VALUES:"Flight Date"::VARCHAR, R.RAW_VALUES:"Flight Date"::VARCHAR)
            WHEN 'USA' THEN COALESCE(R.NORMALIZED_VALUES:"FlightDate"::VARCHAR, R.RAW_VALUES:"FlightDate"::VARCHAR)
        END AS LAST_FLIGHT_DATE_PARSE_VALUE,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN R.RAW_VALUES:"Tier Type"::VARCHAR
            WHEN 'IND' THEN R.RAW_VALUES:"TierCode"::VARCHAR
            WHEN 'USA' THEN R.RAW_VALUES:"TierCode"::VARCHAR
        END AS TIER_CODE_RAW,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN R.RAW_VALUES:"Date of Birth"::VARCHAR
            WHEN 'IND' THEN R.RAW_VALUES:"DOB"::VARCHAR
            WHEN 'USA' THEN R.RAW_VALUES:"DOB"::VARCHAR
        END AS DOB_RAW,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN COALESCE(R.NORMALIZED_VALUES:"Date of Birth"::VARCHAR, R.RAW_VALUES:"Date of Birth"::VARCHAR)
            WHEN 'IND' THEN COALESCE(R.NORMALIZED_VALUES:"DOB"::VARCHAR, R.RAW_VALUES:"DOB"::VARCHAR)
            WHEN 'USA' THEN COALESCE(R.NORMALIZED_VALUES:"DOB"::VARCHAR, R.RAW_VALUES:"DOB"::VARCHAR)
        END AS DOB_PARSE_VALUE,
        CASE R.SOURCE_CODE
            WHEN 'AUS' THEN ARRAY_CONTAINS(TO_VARIANT('Date of Birth'), R.SOURCE_COLUMNS_PRESENT)
            WHEN 'IND' THEN ARRAY_CONTAINS(TO_VARIANT('DOB'), R.SOURCE_COLUMNS_PRESENT)
            WHEN 'USA' THEN ARRAY_CONTAINS(TO_VARIANT('DOB'), R.SOURCE_COLUMNS_PRESENT)
        END AS DOB_COLUMN_PRESENT,
        COALESCE(R.RAW_VALUES:"Agent Name"::VARCHAR, R.RAW_VALUES:"Agent_Name"::VARCHAR) AS AGENT_NAME_RAW,
        R.RAW_VALUES:"State"::VARCHAR AS STATE_RAW,
        R.RAW_VALUES:"Country"::VARCHAR AS COUNTRY_RAW,
        R.RAW_VALUES:"Post Code"::VARCHAR AS POST_CODE_RAW,
        COALESCE(R.RAW_VALUES:"Active Member"::VARCHAR, R.RAW_VALUES:"Is_Active"::VARCHAR) AS ACTIVE_MEMBER_RAW,
        CASE R.SOURCE_FILENAME
            WHEN 'AUS.xlsx' THEN IFF(R.SOURCE_CODE = 'AUS', 'AUS', NULL)
            WHEN 'IND.csv' THEN IFF(R.SOURCE_CODE = 'IND', 'IND', NULL)
            WHEN 'USA.csv' THEN IFF(R.SOURCE_CODE = 'USA', 'USA', NULL)
        END AS ROUTED_COUNTRY_CODE,
        CASE WHEN (R.SOURCE_FILENAME = 'AUS.xlsx' AND R.SOURCE_CODE = 'AUS')
                   OR (R.SOURCE_FILENAME = 'IND.csv' AND R.SOURCE_CODE = 'IND')
                   OR (R.SOURCE_FILENAME = 'USA.csv' AND R.SOURCE_CODE = 'USA')
             THEN 'FILENAME_SAMPLE_ADAPTER' END AS ROUTING_METHOD
    FROM RAW_MEMBER_LANDING R
    WHERE R.RUN_ID = $RUN_ID
), DATE_CANDIDATES AS (
    SELECT B.*,
        CASE
            WHEN SOURCE_CODE = 'AUS' THEN COALESCE(
                TRY_TO_DATE(ENROLLMENT_DATE_PARSE_VALUE, 'YYYY-MM-DD'),
                TRY_TO_DATE(ENROLLMENT_DATE_PARSE_VALUE, 'YYYY-MM-DD HH24:MI:SS.FF'),
                TRY_TO_DATE(ENROLLMENT_DATE_PARSE_VALUE, 'YYYY-MM-DD HH24:MI:SS'),
                TRY_TO_DATE(ENROLLMENT_DATE_PARSE_VALUE, 'YYYYMMDD'))
            WHEN SOURCE_CODE = 'IND' THEN TRY_TO_DATE(ENROLLMENT_DATE_PARSE_VALUE, 'MM/DD/YYYY')
            WHEN SOURCE_CODE = 'USA' AND LENGTH(ENROLLMENT_DATE_PARSE_VALUE) = 8
                THEN TRY_TO_DATE(ENROLLMENT_DATE_PARSE_VALUE, 'MMDDYYYY')
            WHEN SOURCE_CODE = 'USA' AND LENGTH(ENROLLMENT_DATE_PARSE_VALUE) = 7
                THEN TRY_TO_DATE(LPAD(SUBSTR(ENROLLMENT_DATE_PARSE_VALUE, 1, 1), 2, '0') ||
                    LPAD(SUBSTR(ENROLLMENT_DATE_PARSE_VALUE, 2, 2), 2, '0') ||
                    SUBSTR(ENROLLMENT_DATE_PARSE_VALUE, 4, 4), 'MMDDYYYY')
        END AS ENROLL_CANDIDATE_1,
        CASE WHEN SOURCE_CODE = 'USA' AND LENGTH(ENROLLMENT_DATE_PARSE_VALUE) = 7
            THEN TRY_TO_DATE(LPAD(SUBSTR(ENROLLMENT_DATE_PARSE_VALUE, 1, 2), 2, '0') ||
                LPAD(SUBSTR(ENROLLMENT_DATE_PARSE_VALUE, 3, 1), 2, '0') ||
                SUBSTR(ENROLLMENT_DATE_PARSE_VALUE, 4, 4), 'MMDDYYYY') END AS ENROLL_CANDIDATE_2,
        CASE
            WHEN SOURCE_CODE = 'AUS' THEN COALESCE(
                TRY_TO_DATE(LAST_FLIGHT_DATE_PARSE_VALUE, 'YYYY-MM-DD'),
                TRY_TO_DATE(LAST_FLIGHT_DATE_PARSE_VALUE, 'YYYY-MM-DD HH24:MI:SS.FF'),
                TRY_TO_DATE(LAST_FLIGHT_DATE_PARSE_VALUE, 'YYYY-MM-DD HH24:MI:SS'),
                TRY_TO_DATE(LAST_FLIGHT_DATE_PARSE_VALUE, 'YYYYMMDD'))
            WHEN SOURCE_CODE = 'IND' THEN TRY_TO_DATE(LAST_FLIGHT_DATE_PARSE_VALUE, 'MM/DD/YYYY')
            WHEN SOURCE_CODE = 'USA' AND LENGTH(LAST_FLIGHT_DATE_PARSE_VALUE) = 8
                THEN TRY_TO_DATE(LAST_FLIGHT_DATE_PARSE_VALUE, 'MMDDYYYY')
            WHEN SOURCE_CODE = 'USA' AND LENGTH(LAST_FLIGHT_DATE_PARSE_VALUE) = 7
                THEN TRY_TO_DATE(LPAD(SUBSTR(LAST_FLIGHT_DATE_PARSE_VALUE, 1, 1), 2, '0') ||
                    LPAD(SUBSTR(LAST_FLIGHT_DATE_PARSE_VALUE, 2, 2), 2, '0') ||
                    SUBSTR(LAST_FLIGHT_DATE_PARSE_VALUE, 4, 4), 'MMDDYYYY')
        END AS FLIGHT_CANDIDATE_1,
        CASE WHEN SOURCE_CODE = 'USA' AND LENGTH(LAST_FLIGHT_DATE_PARSE_VALUE) = 7
            THEN TRY_TO_DATE(LPAD(SUBSTR(LAST_FLIGHT_DATE_PARSE_VALUE, 1, 2), 2, '0') ||
                LPAD(SUBSTR(LAST_FLIGHT_DATE_PARSE_VALUE, 3, 1), 2, '0') ||
                SUBSTR(LAST_FLIGHT_DATE_PARSE_VALUE, 4, 4), 'MMDDYYYY') END AS FLIGHT_CANDIDATE_2,
        CASE
            WHEN SOURCE_CODE = 'AUS' THEN COALESCE(
                TRY_TO_DATE(DOB_PARSE_VALUE, 'YYYY-MM-DD'),
                TRY_TO_DATE(DOB_PARSE_VALUE, 'YYYY-MM-DD HH24:MI:SS.FF'),
                TRY_TO_DATE(DOB_PARSE_VALUE, 'YYYY-MM-DD HH24:MI:SS'),
                TRY_TO_DATE(DOB_PARSE_VALUE, 'YYYYMMDD'))
            WHEN SOURCE_CODE = 'IND' THEN TRY_TO_DATE(DOB_PARSE_VALUE, 'MM/DD/YYYY')
            WHEN SOURCE_CODE = 'USA' AND LENGTH(DOB_PARSE_VALUE) = 8 THEN TRY_TO_DATE(DOB_PARSE_VALUE, 'MMDDYYYY')
            WHEN SOURCE_CODE = 'USA' AND LENGTH(DOB_PARSE_VALUE) = 7 THEN
                TRY_TO_DATE(LPAD(SUBSTR(DOB_PARSE_VALUE, 1, 1), 2, '0') ||
                    LPAD(SUBSTR(DOB_PARSE_VALUE, 2, 2), 2, '0') ||
                    SUBSTR(DOB_PARSE_VALUE, 4, 4), 'MMDDYYYY')
        END AS DOB_CANDIDATE_1,
        CASE WHEN SOURCE_CODE = 'USA' AND LENGTH(DOB_PARSE_VALUE) = 7 THEN
            TRY_TO_DATE(LPAD(SUBSTR(DOB_PARSE_VALUE, 1, 2), 2, '0') ||
                LPAD(SUBSTR(DOB_PARSE_VALUE, 3, 1), 2, '0') ||
                SUBSTR(DOB_PARSE_VALUE, 4, 4), 'MMDDYYYY') END AS DOB_CANDIDATE_2
    FROM BASE B
), DATE_VALUES AS (
    SELECT D.*,
        IFF(LENGTH(MEMBER_NAME_RAW) <= 255, MEMBER_NAME_RAW, NULL) AS MEMBER_NAME,
        IFF(LENGTH(MEMBER_ID_RAW) <= 18, MEMBER_ID_RAW, NULL) AS MEMBER_ID,
        IFF(LENGTH(TIER_CODE_RAW) <= 5, TIER_CODE_RAW, NULL) AS TIER_CODE,
        IFF(LENGTH(AGENT_NAME_RAW) <= 255, AGENT_NAME_RAW, NULL) AS AGENT_NAME,
        IFF(LENGTH(STATE_RAW) <= 5, STATE_RAW, NULL) AS STATE,
        IFF(LENGTH(COUNTRY_RAW) <= 5, COUNTRY_RAW, NULL) AS COUNTRY,
        IFF(LENGTH(ACTIVE_MEMBER_RAW) <= 1, ACTIVE_MEMBER_RAW, NULL) AS ACTIVE_MEMBER,
        CASE WHEN ENROLL_CANDIDATE_1 = ENROLL_CANDIDATE_2 OR ENROLL_CANDIDATE_2 IS NULL
             THEN ENROLL_CANDIDATE_1 WHEN ENROLL_CANDIDATE_1 IS NULL THEN ENROLL_CANDIDATE_2 END AS ENROLLMENT_DATE,
        CASE WHEN ENROLLMENT_DATE_RAW IS NULL OR TRIM(ENROLLMENT_DATE_RAW) = ''
                       OR UPPER(TRIM(ENROLLMENT_DATE_RAW)) = 'NULL' THEN 'MISSING'
             WHEN ENROLL_CANDIDATE_1 IS NOT NULL AND ENROLL_CANDIDATE_2 IS NOT NULL
                  AND ENROLL_CANDIDATE_1 <> ENROLL_CANDIDATE_2 THEN 'AMBIGUOUS'
             WHEN ENROLL_CANDIDATE_1 IS NULL AND ENROLL_CANDIDATE_2 IS NULL THEN 'INVALID'
             ELSE 'VALID' END AS ENROLLMENT_DATE_STATUS,
        CASE WHEN FLIGHT_CANDIDATE_1 = FLIGHT_CANDIDATE_2 OR FLIGHT_CANDIDATE_2 IS NULL
             THEN FLIGHT_CANDIDATE_1 WHEN FLIGHT_CANDIDATE_1 IS NULL THEN FLIGHT_CANDIDATE_2 END AS LAST_FLIGHT_DATE,
        CASE WHEN LAST_FLIGHT_DATE_RAW IS NULL OR TRIM(LAST_FLIGHT_DATE_RAW) = ''
                       OR UPPER(TRIM(LAST_FLIGHT_DATE_RAW)) = 'NULL' THEN 'MISSING'
             WHEN FLIGHT_CANDIDATE_1 IS NOT NULL AND FLIGHT_CANDIDATE_2 IS NOT NULL
                  AND FLIGHT_CANDIDATE_1 <> FLIGHT_CANDIDATE_2 THEN 'AMBIGUOUS'
             WHEN FLIGHT_CANDIDATE_1 IS NULL AND FLIGHT_CANDIDATE_2 IS NULL THEN 'INVALID'
             ELSE 'VALID' END AS LAST_FLIGHT_DATE_STATUS,
        CASE WHEN DOB_CANDIDATE_1 = DOB_CANDIDATE_2 OR DOB_CANDIDATE_2 IS NULL
             THEN DOB_CANDIDATE_1 WHEN DOB_CANDIDATE_1 IS NULL THEN DOB_CANDIDATE_2 END AS DOB,
        CASE WHEN NOT COALESCE(DOB_COLUMN_PRESENT, FALSE) THEN 'ABSENT'
             WHEN DOB_RAW IS NULL OR TRIM(DOB_RAW) = '' OR UPPER(TRIM(DOB_RAW)) = 'NULL' THEN 'MISSING'
             WHEN DOB_CANDIDATE_1 IS NOT NULL AND DOB_CANDIDATE_2 IS NOT NULL
                  AND DOB_CANDIDATE_1 <> DOB_CANDIDATE_2 THEN 'AMBIGUOUS'
             WHEN DOB_CANDIDATE_1 IS NULL AND DOB_CANDIDATE_2 IS NULL THEN 'INVALID'
             ELSE 'VALID' END AS DOB_STATUS
    FROM DATE_CANDIDATES D
), SCORED AS (
    SELECT V.*,
        COALESCE(COUNT_IF(MEMBER_NAME_RAW IS NOT NULL AND TRIM(MEMBER_NAME_RAW) <> '') OVER
            (PARTITION BY RUN_ID, BATCH_ID, SOURCE_CODE, MEMBER_NAME_RAW), 0) AS MEMBER_NAME_KEY_COUNT,
        COALESCE(COUNT_IF(MEMBER_ID_RAW IS NOT NULL AND TRIM(MEMBER_ID_RAW) <> '') OVER
            (PARTITION BY RUN_ID, BATCH_ID, SOURCE_CODE, MEMBER_ID_RAW), 0) AS SOURCE_MEMBER_ID_COUNT
    FROM DATE_VALUES V
)
SELECT S.*,
    CASE WHEN MEMBER_NAME IS NULL OR TRIM(MEMBER_NAME) = ''
           OR MEMBER_ID_RAW IS NULL OR TRIM(MEMBER_ID_RAW) = ''
           OR LENGTH(MEMBER_NAME_RAW) > 255 OR LENGTH(MEMBER_ID_RAW) > 18
           OR LENGTH(TIER_CODE_RAW) > 5 OR LENGTH(AGENT_NAME_RAW) > 255
           OR LENGTH(STATE_RAW) > 5 OR LENGTH(COUNTRY_RAW) > 5
           OR LENGTH(ACTIVE_MEMBER_RAW) > 1
           OR ENROLLMENT_DATE_STATUS IN ('MISSING', 'INVALID', 'AMBIGUOUS')
           OR (DOB IS NOT NULL AND DOB > $AS_OF_DATE)
           OR MEMBER_NAME_KEY_COUNT > 1
         THEN 'QUARANTINED'
         WHEN LAST_FLIGHT_DATE_STATUS IN ('INVALID', 'AMBIGUOUS', 'MISSING')
           OR DOB_STATUS = 'INVALID'
           OR UPPER(TRIM(DOB_RAW)) = 'NULL'
           OR (POST_CODE_RAW IS NOT NULL AND (
                TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6) IS NULL
                OR LENGTH(POST_CODE_RAW) > 5
                OR TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6) <> TRUNC(TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6))
                OR ABS(TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6)) > 99999))
           OR (COUNTRY_RAW IS NOT NULL AND UPPER(TRIM(COUNTRY_RAW)) <> ROUTED_COUNTRY_CODE)
           OR ROUTED_COUNTRY_CODE IS NULL
           OR (ENROLLMENT_DATE IS NOT NULL AND ENROLLMENT_DATE > $AS_OF_DATE)
           OR (LAST_FLIGHT_DATE IS NOT NULL AND LAST_FLIGHT_DATE > $AS_OF_DATE)
           OR SOURCE_MEMBER_ID_COUNT > 1
         THEN 'WARNING' ELSE 'ACCEPTED' END AS DISPOSITION,
    CASE WHEN DOB IS NULL OR DOB > $AS_OF_DATE THEN NULL
         -- Comparing MMDD makes Feb. 29 birthdays fall on March 1 in non-leap years.
         ELSE DATEDIFF(year, DOB, $AS_OF_DATE) -
              IFF(TO_CHAR($AS_OF_DATE, 'MMDD') < TO_CHAR(DOB, 'MMDD'), 1, 0) END::NUMBER(38,0) AS AGE,
    CASE WHEN LAST_FLIGHT_DATE IS NULL OR LAST_FLIGHT_DATE > $AS_OF_DATE THEN NULL
         ELSE DATEDIFF(day, LAST_FLIGHT_DATE, $AS_OF_DATE) > 90 END AS STALE_MEMBER
FROM SCORED S;

CREATE OR REPLACE TEMP TABLE MEMBER_ISSUE_CANDIDATE AS
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation' AS ISSUE_CATEGORY, 'MEMBER_NAME_REQUIRED' AS RULE_CODE,
       'ERROR' AS SEVERITY, 'MEMBER_NAME' AS FIELD_NAME,
       'Required Member Name is missing or blank.' AS DETAIL
FROM MEMBER_CANDIDATE WHERE MEMBER_NAME_RAW IS NULL OR TRIM(MEMBER_NAME_RAW) = ''
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'MEMBER_ID_REQUIRED', 'ERROR', 'MEMBER_ID',
       'Required Member ID is missing or blank.'
FROM MEMBER_CANDIDATE WHERE MEMBER_ID_RAW IS NULL OR TRIM(MEMBER_ID_RAW) = ''
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'ENROLLMENT_DATE_' || ENROLLMENT_DATE_STATUS, 'ERROR', 'ENROLLMENT_DATE',
       'Required enrollment date is missing, invalid, or ambiguous; raw value retained.'
FROM MEMBER_CANDIDATE WHERE ENROLLMENT_DATE_STATUS <> 'VALID'
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'FUTURE_DOB', 'ERROR', 'DOB', 'DOB is after the explicit AS_OF_DATE.'
FROM MEMBER_CANDIDATE WHERE DOB IS NOT NULL AND DOB > $AS_OF_DATE
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'DUPLICATE_MEMBER_NAME', 'ERROR', 'MEMBER_NAME',
       'Duplicate Member Name within the provisional run/source-country batch scope.'
FROM MEMBER_CANDIDATE WHERE MEMBER_NAME_KEY_COUNT > 1
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'MEMBER_NAME_TOO_LONG', 'ERROR', 'MEMBER_NAME',
       'Member Name exceeds the assessment maximum length of 255.'
FROM MEMBER_CANDIDATE WHERE LENGTH(MEMBER_NAME_RAW) > 255
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'MEMBER_ID_TOO_LONG', 'ERROR', 'MEMBER_ID',
       'Member ID exceeds the assessment maximum length of 18.'
FROM MEMBER_CANDIDATE WHERE LENGTH(MEMBER_ID_RAW) > 18
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'TIER_CODE_TOO_LONG', 'ERROR', 'TIER_CODE',
       'Tier Code exceeds the assessment maximum length of 5.'
FROM MEMBER_CANDIDATE WHERE LENGTH(TIER_CODE_RAW) > 5
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'AGENT_NAME_TOO_LONG', 'ERROR', 'AGENT_NAME',
       'Agent Name exceeds the assessment maximum length of 255.'
FROM MEMBER_CANDIDATE WHERE LENGTH(AGENT_NAME_RAW) > 255
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'STATE_TOO_LONG', 'ERROR', 'STATE', 'State exceeds the assessment maximum length of 5.'
FROM MEMBER_CANDIDATE WHERE LENGTH(STATE_RAW) > 5
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'COUNTRY_TOO_LONG', 'ERROR', 'COUNTRY', 'Country exceeds the assessment maximum length of 5.'
FROM MEMBER_CANDIDATE WHERE LENGTH(COUNTRY_RAW) > 5
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'ACTIVE_MEMBER_TOO_LONG', 'ERROR', 'ACTIVE_MEMBER',
       'Active Member exceeds the assessment maximum length of 1.'
FROM MEMBER_CANDIDATE WHERE LENGTH(ACTIVE_MEMBER_RAW) > 1
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'DUPLICATE_SOURCE_MEMBER_ID', 'WARNING', 'MEMBER_ID',
       'Duplicate source-local Member ID; assessment does not declare Member ID as a key.'
FROM MEMBER_CANDIDATE WHERE SOURCE_MEMBER_ID_COUNT > 1
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'LAST_FLIGHT_DATE_' || LAST_FLIGHT_DATE_STATUS, 'WARNING', 'LAST_FLIGHT_DATE',
       'Optional flight date is missing, invalid, or ambiguous; raw value retained.'
FROM MEMBER_CANDIDATE WHERE LAST_FLIGHT_DATE_STATUS IN ('INVALID', 'AMBIGUOUS', 'MISSING')
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'DOB_INVALID', 'WARNING', 'DOB',
       'Optional DOB is invalid; raw value retained and derived Age is NULL.'
FROM MEMBER_CANDIDATE WHERE DOB_STATUS = 'INVALID'
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'DOB_AMBIGUOUS', 'WARNING', 'DOB',
       'DOB has multiple valid compact-date interpretations; raw value retained and Age is NULL.'
FROM MEMBER_CANDIDATE WHERE DOB_STATUS = 'AMBIGUOUS'
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'FUTURE_ENROLLMENT_DATE', 'WARNING', 'ENROLLMENT_DATE',
       'Provisional warning for enrollment date after AS_OF_DATE.'
FROM MEMBER_CANDIDATE WHERE ENROLLMENT_DATE > $AS_OF_DATE
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'FUTURE_FLIGHT_DATE', 'WARNING', 'LAST_FLIGHT_DATE',
       'Provisional warning for flight date after AS_OF_DATE; Stale_Member is NULL.'
FROM MEMBER_CANDIDATE WHERE LAST_FLIGHT_DATE > $AS_OF_DATE
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'DOB_LITERAL_NULL', 'WARNING', 'DOB',
       'DOB contains the literal NULL marker; raw value retained.'
FROM MEMBER_CANDIDATE WHERE UPPER(TRIM(DOB_RAW)) = 'NULL'
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'validation', 'POST_CODE_INVALID', 'WARNING', 'POST_CODE',
       'Post Code is not an integer in the specified five-digit range; raw value retained.'
FROM MEMBER_CANDIDATE
WHERE POST_CODE_RAW IS NOT NULL AND (
    TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6) IS NULL
    OR LENGTH(POST_CODE_RAW) > 5
    OR TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6) <> TRUNC(TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6))
    OR ABS(TRY_TO_DECIMAL(POST_CODE_RAW, 38, 6)) > 99999
)
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'routing', 'SOURCE_COUNTRY_DIFFERS_FROM_SAMPLE_ROUTE', 'WARNING', 'Country',
       'Source Country differs from filename-based demonstration route; no correction was inferred.'
FROM MEMBER_CANDIDATE
WHERE COUNTRY_RAW IS NOT NULL AND UPPER(TRIM(COUNTRY_RAW)) <> ROUTED_COUNTRY_CODE
UNION ALL
SELECT RUN_ID, ARTIFACT_ID, SOURCE_ROW_NUMBER, SOURCE_SHEET_KEY,
       'routing', 'COUNTRY_ROUTE_UNMAPPED_SOURCE', 'WARNING', 'SOURCE_FILENAME',
       'No exact local filename/source-code adapter mapping is configured.'
FROM MEMBER_CANDIDATE WHERE ROUTED_COUNTRY_CODE IS NULL;

-- Rebuild this run's staging/quality outputs deterministically; raw landing is
-- append-only and is never changed by these transformations.
BEGIN TRANSACTION;
DELETE FROM MEMBER_STAGING WHERE RUN_ID = $RUN_ID;
DELETE FROM DATA_QUALITY_ISSUE WHERE RUN_ID = $RUN_ID AND ENTITY_TYPE = 'MEMBER';

INSERT INTO MEMBER_STAGING (
    RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_CODE, SOURCE_FILENAME, SOURCE_SHEET,
    SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER, AS_OF_DATE, SOURCE_COLUMNS_PRESENT, RAW_VALUES,
    MEMBER_NAME, MEMBER_NAME_RAW, MEMBER_ID, MEMBER_ID_RAW,
    ENROLLMENT_DATE, ENROLLMENT_DATE_RAW, ENROLLMENT_DATE_STATUS,
    LAST_FLIGHT_DATE, LAST_FLIGHT_DATE_RAW, LAST_FLIGHT_DATE_STATUS, TIER_CODE,
    TIER_CODE_RAW, AGENT_NAME, AGENT_NAME_RAW, STATE, STATE_RAW, COUNTRY, COUNTRY_RAW,
    POST_CODE, POST_CODE_RAW, DOB, DOB_RAW, DOB_STATUS,
    ACTIVE_MEMBER, ACTIVE_MEMBER_RAW, AGE, STALE_MEMBER, ROUTED_COUNTRY_CODE, ROUTING_METHOD,
