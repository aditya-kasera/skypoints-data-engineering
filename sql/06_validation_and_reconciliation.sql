-- Operational review queries and database-derived reconciliation.
USE SCHEMA SKYPOINTS_ASSESSMENT;
SET RUN_ID = 'REPLACE_WITH_RUN_ID';

-- Assessment-mandatory fields (Member Name, Member ID, Enrollment Date).
SELECT RUN_ID, ARTIFACT_ID, SOURCE_FILENAME, SOURCE_ROW_NUMBER,
       MEMBER_NAME_RAW, MEMBER_ID_RAW, ENROLLMENT_DATE_RAW, DISPOSITION
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID
  AND (NULLIF(TRIM(MEMBER_NAME_RAW), '') IS NULL
       OR NULLIF(TRIM(MEMBER_ID_RAW), '') IS NULL
       OR ENROLLMENT_DATE_STATUS <> 'VALID');

-- Provisional Member_Name key scope: one run + source-country batch across
-- artifacts sharing the batch ID. Different source-country batches are isolated.
SELECT RUN_ID, BATCH_ID, SOURCE_CODE, MEMBER_NAME_RAW,
       ARRAY_AGG(DISTINCT ARTIFACT_ID) AS ARTIFACTS,
       COUNT(*) AS DUPLICATE_COUNT
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND NULLIF(TRIM(MEMBER_NAME_RAW), '') IS NOT NULL
GROUP BY RUN_ID, BATCH_ID, SOURCE_CODE, MEMBER_NAME_RAW
HAVING COUNT(*) > 1;

-- Member ID is mandatory but not an assessment key: duplicates are warnings.
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_CODE, MEMBER_ID_RAW,
       MAX(SOURCE_MEMBER_ID_COUNT) AS DUPLICATE_COUNT
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND SOURCE_MEMBER_ID_COUNT > 1
GROUP BY RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_CODE, MEMBER_ID_RAW;

-- Transaction ID duplicates are scoped to one run and source batch. The
-- assessment does not establish uniqueness across independent batches.
SELECT RUN_ID, BATCH_ID, TXN_ID, COUNT(*) AS DUPLICATE_COUNT,
       ARRAY_AGG(DISTINCT ARTIFACT_ID) AS ARTIFACTS
FROM REDEMPTION_STAGING
WHERE RUN_ID = $RUN_ID AND NULLIF(TRIM(TXN_ID), '') IS NOT NULL
GROUP BY RUN_ID, BATCH_ID, TXN_ID
HAVING COUNT(*) > 1;

-- Invalid and ambiguous date values remain in RAW_VALUES and raw date columns.
SELECT RUN_ID, ARTIFACT_ID, SOURCE_FILENAME, SOURCE_ROW_NUMBER,
       ENROLLMENT_DATE_RAW, ENROLLMENT_DATE_STATUS,
       LAST_FLIGHT_DATE_RAW, LAST_FLIGHT_DATE_STATUS, DOB_RAW, DOB_STATUS
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID
  AND (ENROLLMENT_DATE_STATUS IN ('INVALID', 'AMBIGUOUS')
       OR LAST_FLIGHT_DATE_STATUS IN ('INVALID', 'AMBIGUOUS')
       OR DOB_STATUS IN ('INVALID', 'AMBIGUOUS'));

-- All quarantined members remain queryable in staging; curated targets exclude them.
SELECT * FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND DISPOSITION = 'QUARANTINED';

-- Quality issue details include date, key, field-length and referential checks.
SELECT * FROM DATA_QUALITY_ISSUE
WHERE RUN_ID = $RUN_ID
ORDER BY ARTIFACT_ID, ENTITY_TYPE, SOURCE_ROW_NUMBER, PAYLOAD_INDEX,
         TRANSACTION_INDEX, ISSUE_ORDINAL;

-- Unmatched references are intentionally retained as warnings in the flattened table.
SELECT F.RUN_ID, F.ARTIFACT_ID, F.PAYLOAD_INDEX, F.TRANSACTION_INDEX,
       F.MEMBER_ID, F.TXN_ID, F.DISPOSITION, Q.RULE_CODE, Q.DETAIL
FROM FLATTENED_REDEMPTION F
JOIN REDEMPTION_PARENT_STAGING P
  ON P.RUN_ID = F.RUN_ID AND P.ARTIFACT_ID = F.ARTIFACT_ID
 AND P.PAYLOAD_INDEX = F.PAYLOAD_INDEX
JOIN DATA_QUALITY_ISSUE Q
  ON Q.RUN_ID = F.RUN_ID AND Q.ARTIFACT_ID = F.ARTIFACT_ID
 AND Q.PAYLOAD_INDEX = F.PAYLOAD_INDEX
 AND Q.TRANSACTION_INDEX = F.TRANSACTION_INDEX
WHERE F.RUN_ID = $RUN_ID AND F.DISPOSITION = 'WARNING'
  AND P.DISPOSITION = 'ACCEPTED'
  AND Q.RULE_CODE = 'MEMBER_REFERENCE_UNMATCHED';

-- Parent payload outcomes remain queryable even when they produce zero child rows.
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, PAYLOAD_INDEX, PARENT_MEMBER_ID,
       FEED_DATE_RAW, FEED_DATE, TRANSACTION_ARRAY_PRESENT, TRANSACTION_COUNT, DISPOSITION
FROM REDEMPTION_PARENT_STAGING
WHERE RUN_ID = $RUN_ID
ORDER BY ARTIFACT_ID, PAYLOAD_INDEX;

-- Report source Country values that differ from sample filename routing. This
-- is an anomaly report only; no country alias or correction is inferred.
SELECT RUN_ID, ARTIFACT_ID, SOURCE_FILENAME, SOURCE_ROW_NUMBER,
       COUNTRY_RAW, ROUTED_COUNTRY_CODE
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND COUNTRY_RAW IS NOT NULL
  AND UPPER(TRIM(COUNTRY_RAW)) <> ROUTED_COUNTRY_CODE;

CREATE OR REPLACE TEMP TABLE RAW_CHILD_COUNTS AS
SELECT R.RUN_ID, R.ARTIFACT_ID, COUNT(F.INDEX) AS READ_COUNT
FROM RAW_REDEMPTION_LANDING R,
     LATERAL FLATTEN(INPUT => R.PAYLOAD:"redemptions", OUTER => TRUE) F
WHERE R.RUN_ID = $RUN_ID
GROUP BY R.RUN_ID, R.ARTIFACT_ID;

CREATE OR REPLACE TEMP TABLE EXPECTED_RECONCILIATION AS
SELECT M.RUN_ID, M.ARTIFACT_ID, 'member_record' AS SCOPE,
       COUNT(*) AS READ_COUNT,
       COALESCE(COUNT_IF(M.DISPOSITION = 'ACCEPTED'), 0) AS ACCEPTED_COUNT,
       COALESCE(COUNT_IF(M.DISPOSITION = 'WARNING'), 0) AS WARNED_COUNT,
       COALESCE(COUNT_IF(M.DISPOSITION = 'QUARANTINED'), 0) AS QUARANTINED_COUNT,
       COALESCE(COUNT_IF(M.DISPOSITION <> 'QUARANTINED'), 0) AS TRANSFORMED_COUNT,
       0 AS UNMATCHED_COUNT,
       (SELECT COUNT(*) FROM RAW_MEMBER_LANDING R
        WHERE R.RUN_ID = M.RUN_ID AND R.ARTIFACT_ID = M.ARTIFACT_ID) AS RAW_PERSISTED_COUNT,
       (SELECT COUNT(*) FROM MEMBER_AUS_TARGET T
        WHERE T.RUN_ID = M.RUN_ID AND T.ARTIFACT_ID = M.ARTIFACT_ID)
       + (SELECT COUNT(*) FROM MEMBER_IND_TARGET T
          WHERE T.RUN_ID = M.RUN_ID AND T.ARTIFACT_ID = M.ARTIFACT_ID)
       + (SELECT COUNT(*) FROM MEMBER_USA_TARGET T
          WHERE T.RUN_ID = M.RUN_ID AND T.ARTIFACT_ID = M.ARTIFACT_ID) AS CURATED_PERSISTED_COUNT
FROM MEMBER_STAGING M WHERE M.RUN_ID = $RUN_ID
GROUP BY M.RUN_ID, M.ARTIFACT_ID
UNION ALL
SELECT R.RUN_ID, R.ARTIFACT_ID, 'redemption_parent',
       COUNT(*) AS READ_COUNT,
       COALESCE(COUNT_IF(P.DISPOSITION = 'ACCEPTED'), 0),
       COALESCE(COUNT_IF(P.DISPOSITION = 'WARNING'), 0),
       COALESCE(COUNT_IF(P.DISPOSITION = 'QUARANTINED'), 0),
       0, 0, COUNT(*) AS RAW_PERSISTED_COUNT, 0
FROM RAW_REDEMPTION_LANDING R
LEFT JOIN REDEMPTION_PARENT_STAGING P
  ON P.RUN_ID = R.RUN_ID AND P.ARTIFACT_ID = R.ARTIFACT_ID
 AND P.PAYLOAD_INDEX = R.PAYLOAD_INDEX
WHERE R.RUN_ID = $RUN_ID
GROUP BY R.RUN_ID, R.ARTIFACT_ID
UNION ALL
SELECT C.RUN_ID, C.ARTIFACT_ID, 'redemption_transaction',
       C.READ_COUNT,
       COALESCE(COUNT_IF(T.DISPOSITION = 'ACCEPTED'), 0),
       COALESCE(COUNT_IF(T.DISPOSITION = 'WARNING'), 0),
       COALESCE(COUNT_IF(T.DISPOSITION = 'QUARANTINED'), 0),
       COUNT(T.TRANSACTION_INDEX) AS TRANSFORMED_COUNT,
       (SELECT COUNT(*) FROM (
            SELECT DISTINCT F.PAYLOAD_INDEX, F.TRANSACTION_INDEX
            FROM FLATTENED_REDEMPTION F
            JOIN REDEMPTION_PARENT_STAGING P
              ON P.RUN_ID = F.RUN_ID AND P.ARTIFACT_ID = F.ARTIFACT_ID
             AND P.PAYLOAD_INDEX = F.PAYLOAD_INDEX
            JOIN DATA_QUALITY_ISSUE Q
              ON Q.RUN_ID = F.RUN_ID AND Q.ARTIFACT_ID = F.ARTIFACT_ID
             AND Q.PAYLOAD_INDEX = F.PAYLOAD_INDEX
             AND Q.TRANSACTION_INDEX = F.TRANSACTION_INDEX
            WHERE F.RUN_ID = C.RUN_ID AND F.ARTIFACT_ID = C.ARTIFACT_ID
              AND F.DISPOSITION = 'WARNING' AND P.DISPOSITION = 'ACCEPTED'
              AND Q.RULE_CODE = 'MEMBER_REFERENCE_UNMATCHED'
        ) AS ELIGIBLE_UNMATCHED),
       COALESCE(COUNT_IF(T.TRANSACTION_INDEX IS NOT NULL AND T.RAW_TRANSACTION IS NOT NULL), 0)
           AS RAW_PERSISTED_COUNT,
       (SELECT COUNT(*) FROM CURATED_REDEMPTION F
        WHERE F.RUN_ID = C.RUN_ID AND F.ARTIFACT_ID = C.ARTIFACT_ID)
           AS CURATED_PERSISTED_COUNT
FROM RAW_CHILD_COUNTS C
LEFT JOIN REDEMPTION_STAGING T
  ON T.RUN_ID = C.RUN_ID AND T.ARTIFACT_ID = C.ARTIFACT_ID
WHERE C.RUN_ID = $RUN_ID
GROUP BY C.RUN_ID, C.ARTIFACT_ID, C.READ_COUNT;

MERGE INTO RUN_RECONCILIATION TARGET
USING EXPECTED_RECONCILIATION SOURCE
   ON TARGET.RUN_ID = SOURCE.RUN_ID
  AND TARGET.ARTIFACT_ID = SOURCE.ARTIFACT_ID
  AND TARGET.SCOPE = SOURCE.SCOPE
WHEN MATCHED THEN UPDATE SET
    READ_COUNT = SOURCE.READ_COUNT,
    ACCEPTED_COUNT = SOURCE.ACCEPTED_COUNT,
    WARNED_COUNT = SOURCE.WARNED_COUNT,
    QUARANTINED_COUNT = SOURCE.QUARANTINED_COUNT,
    TRANSFORMED_COUNT = SOURCE.TRANSFORMED_COUNT,
    UNMATCHED_COUNT = SOURCE.UNMATCHED_COUNT,
    RAW_PERSISTED_COUNT = SOURCE.RAW_PERSISTED_COUNT,
    CURATED_PERSISTED_COUNT = SOURCE.CURATED_PERSISTED_COUNT,
    RECONCILED_AT_UTC = CURRENT_TIMESTAMP()::TIMESTAMP_TZ
WHEN NOT MATCHED THEN INSERT (
    RUN_ID, ARTIFACT_ID, SCOPE, READ_COUNT, ACCEPTED_COUNT, WARNED_COUNT,
    QUARANTINED_COUNT, TRANSFORMED_COUNT, UNMATCHED_COUNT,
    RAW_PERSISTED_COUNT, CURATED_PERSISTED_COUNT, RECONCILED_AT_UTC
) VALUES (
    SOURCE.RUN_ID, SOURCE.ARTIFACT_ID, SOURCE.SCOPE, SOURCE.READ_COUNT,
    SOURCE.ACCEPTED_COUNT, SOURCE.WARNED_COUNT, SOURCE.QUARANTINED_COUNT,
    SOURCE.TRANSFORMED_COUNT, SOURCE.UNMATCHED_COUNT, SOURCE.RAW_PERSISTED_COUNT,
    SOURCE.CURATED_PERSISTED_COUNT, CURRENT_TIMESTAMP()::TIMESTAMP_TZ
);

-- Reconciliation assertion query: no rows means all persisted values agree.
SELECT E.RUN_ID, E.ARTIFACT_ID, E.SCOPE,
       E.READ_COUNT AS EXPECTED_READ, R.READ_COUNT AS ACTUAL_READ,
       E.ACCEPTED_COUNT AS EXPECTED_ACCEPTED, R.ACCEPTED_COUNT AS ACTUAL_ACCEPTED,
       E.WARNED_COUNT AS EXPECTED_WARNED, R.WARNED_COUNT AS ACTUAL_WARNED,
       E.QUARANTINED_COUNT AS EXPECTED_QUARANTINED, R.QUARANTINED_COUNT AS ACTUAL_QUARANTINED,
       E.TRANSFORMED_COUNT AS EXPECTED_TRANSFORMED, R.TRANSFORMED_COUNT AS ACTUAL_TRANSFORMED,
       E.UNMATCHED_COUNT AS EXPECTED_UNMATCHED, R.UNMATCHED_COUNT AS ACTUAL_UNMATCHED,
       E.RAW_PERSISTED_COUNT AS EXPECTED_RAW, R.RAW_PERSISTED_COUNT AS ACTUAL_RAW,
       E.CURATED_PERSISTED_COUNT AS EXPECTED_CURATED, R.CURATED_PERSISTED_COUNT AS ACTUAL_CURATED
FROM EXPECTED_RECONCILIATION E
LEFT JOIN RUN_RECONCILIATION R
  ON R.RUN_ID = E.RUN_ID AND R.ARTIFACT_ID = E.ARTIFACT_ID AND R.SCOPE = E.SCOPE
WHERE R.RUN_ID IS NULL
   OR E.READ_COUNT <> R.READ_COUNT
   OR E.ACCEPTED_COUNT <> R.ACCEPTED_COUNT
   OR E.WARNED_COUNT <> R.WARNED_COUNT
   OR E.QUARANTINED_COUNT <> R.QUARANTINED_COUNT
   OR E.TRANSFORMED_COUNT <> R.TRANSFORMED_COUNT
   OR E.UNMATCHED_COUNT <> R.UNMATCHED_COUNT
   OR E.RAW_PERSISTED_COUNT <> R.RAW_PERSISTED_COUNT
   OR E.CURATED_PERSISTED_COUNT <> R.CURATED_PERSISTED_COUNT;
