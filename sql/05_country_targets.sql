-- Physical tables satisfy the assessment's country-target DDL requirement.
-- Rows here are per-run sample outputs. The filename router is demonstration
-- provenance only; it is not production member-country truth.
USE SCHEMA SKYPOINTS_ASSESSMENT;
SET RUN_ID = 'REPLACE_WITH_RUN_ID';

CREATE TABLE IF NOT EXISTS MEMBER_AUS_TARGET (
    RUN_ID VARCHAR(100) NOT NULL,
    ARTIFACT_ID VARCHAR(256) NOT NULL,
    BATCH_ID VARCHAR(256) NOT NULL,
    SOURCE_CODE VARCHAR(32) NOT NULL,
    SOURCE_FILENAME VARCHAR(1024) NOT NULL,
    SOURCE_SHEET_KEY VARCHAR(255) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38, 0) NOT NULL,
    MEMBER_NAME VARCHAR(255) NOT NULL,
    MEMBER_ID VARCHAR(18) NOT NULL,
    ENROLLMENT_DATE DATE NOT NULL,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE CHAR(5),
    AGENT_NAME CHAR(255),
    STATE CHAR(5),
    COUNTRY CHAR(5),
    POST_CODE NUMBER(5, 0),
    DOB DATE,
    ACTIVE_MEMBER CHAR(1),
    AGE NUMBER(38, 0),
    STALE_MEMBER BOOLEAN,
    TARGET_COUNTRY_CODE VARCHAR(3) NOT NULL,
    ROUTING_METHOD VARCHAR(64) NOT NULL,
    AS_OF_DATE DATE NOT NULL,
    DISPOSITION VARCHAR(16) NOT NULL,
    CONSTRAINT PK_MEMBER_AUS_TARGET PRIMARY KEY
        (RUN_ID, BATCH_ID, SOURCE_CODE, SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER) NOT ENFORCED,
    CONSTRAINT UQ_MEMBER_AUS_NAME_BATCH UNIQUE
        (RUN_ID, BATCH_ID, SOURCE_CODE, MEMBER_NAME) NOT ENFORCED
);

CREATE TABLE IF NOT EXISTS MEMBER_IND_TARGET LIKE MEMBER_AUS_TARGET;
CREATE TABLE IF NOT EXISTS MEMBER_USA_TARGET LIKE MEMBER_AUS_TARGET;

COMMENT ON COLUMN MEMBER_AUS_TARGET.MEMBER_NAME IS
    'Assessment key flag retained; UNIQUE scope is a provisional source-country batch assumption and Snowflake standard-table constraint is informational.';
COMMENT ON COLUMN MEMBER_AUS_TARGET.MEMBER_ID IS
    'Assessment-mandatory VARCHAR(18), not a key and not a global identity.';
COMMENT ON COLUMN MEMBER_AUS_TARGET.ROUTING_METHOD IS
    'FILENAME_SAMPLE_ADAPTER is limited to AUS.xlsx, IND.csv, and USA.csv demo inputs.';

BEGIN TRANSACTION;
DELETE FROM MEMBER_AUS_TARGET WHERE RUN_ID = $RUN_ID;
DELETE FROM MEMBER_IND_TARGET WHERE RUN_ID = $RUN_ID;
DELETE FROM MEMBER_USA_TARGET WHERE RUN_ID = $RUN_ID;

INSERT INTO MEMBER_AUS_TARGET
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_CODE, SOURCE_FILENAME,
       SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER, MEMBER_NAME, MEMBER_ID,
       ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY,
       POST_CODE, DOB, ACTIVE_MEMBER, AGE, STALE_MEMBER, 'AUS', ROUTING_METHOD,
       AS_OF_DATE, DISPOSITION
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND ROUTED_COUNTRY_CODE = 'AUS'
  AND DISPOSITION <> 'QUARANTINED'
  AND MEMBER_NAME IS NOT NULL AND MEMBER_ID IS NOT NULL AND ENROLLMENT_DATE IS NOT NULL;

INSERT INTO MEMBER_IND_TARGET
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_CODE, SOURCE_FILENAME,
       SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER, MEMBER_NAME, MEMBER_ID,
       ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY,
       POST_CODE, DOB, ACTIVE_MEMBER, AGE, STALE_MEMBER, 'IND', ROUTING_METHOD,
       AS_OF_DATE, DISPOSITION
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND ROUTED_COUNTRY_CODE = 'IND'
  AND DISPOSITION <> 'QUARANTINED'
  AND MEMBER_NAME IS NOT NULL AND MEMBER_ID IS NOT NULL AND ENROLLMENT_DATE IS NOT NULL;

INSERT INTO MEMBER_USA_TARGET
SELECT RUN_ID, ARTIFACT_ID, BATCH_ID, SOURCE_CODE, SOURCE_FILENAME,
       SOURCE_SHEET_KEY, SOURCE_ROW_NUMBER, MEMBER_NAME, MEMBER_ID,
       ENROLLMENT_DATE, LAST_FLIGHT_DATE, TIER_CODE, AGENT_NAME, STATE, COUNTRY,
       POST_CODE, DOB, ACTIVE_MEMBER, AGE, STALE_MEMBER, 'USA', ROUTING_METHOD,
       AS_OF_DATE, DISPOSITION
FROM MEMBER_STAGING
WHERE RUN_ID = $RUN_ID AND ROUTED_COUNTRY_CODE = 'USA'
  AND DISPOSITION <> 'QUARANTINED'
  AND MEMBER_NAME IS NOT NULL AND MEMBER_ID IS NOT NULL AND ENROLLMENT_DATE IS NOT NULL;
COMMIT;

-- No latest-record-wins is performed for supplied rows: they have neither
